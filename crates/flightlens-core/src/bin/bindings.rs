use flightlens_core::{analysis::*, export::*, feedback::*, llm::*, *};
use ts_rs::TS;
fn main() {
    let declarations = [
        SummaryRequest::decl(),
        SummarySlot::decl(),
        LlmStatus::decl(),
        LlmPreview::decl(),
        LlmSummary::decl(),
        Provider::decl(),
        LlmSettings::decl(),
        DigestFirmware::decl(),
        Provenance::decl(),
        DigestParameter::decl(),
        DigestCurve::decl(),
        DigestAudit::decl(),
        InspectorDigest::decl(),
        DiffRowInput::decl(),
        Truncation::decl(),
        DiffDigest::decl(),
        workspace::WorkspaceEntry::decl(),
        workspace::WorkspacePage::decl(),
        Value::decl(),
        Scope::decl(),
        Parameter::decl(),
        Derived::decl(),
        Diagnostic::decl(),
        Command::decl(),
        SyntaxLine::decl(),
        SourceEvidence::decl(),
        Firmware::decl(),
        Port::decl(),
        Mode::decl(),
        ConfigDocument::decl(),
        DocumentView::decl(),
        Artifact::decl(),
        ArtifactView::decl(),
        RecognizedArtifact::decl(),
        SourceDescriptor::decl(),
        RestoredSession::decl(),
        Point::decl(),
        Curve::decl(),
        OsdElement::decl(),
        RuleEvaluation::decl(),
        Inspection::decl(),
        ExportRequest::decl(),
        ValidatedSnippet::decl(),
        Category::decl(),
        Redaction::decl(),
        ReportKind::decl(),
        FeedbackRequest::decl(),
        FeedbackReport::decl(),
    ];
    let text = format!(
        "// Generated by cargo run -p flightlens-core --bin bindings. Do not edit.\n{}\n",
        declarations
            .iter()
            .map(|s| format!("export {s}"))
            .collect::<Vec<_>>()
            .join("\n\n")
    );
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../src/bindings/core.ts");
    if std::env::args().any(|a| a == "--check") {
        assert_eq!(
            std::fs::read_to_string(path)
                .expect("generated bindings missing")
                .replace("\r\n", "\n"),
            text,
            "Generated bindings drifted; run pnpm bindings"
        );
    } else {
        std::fs::write(path, text).unwrap();
    }
}
